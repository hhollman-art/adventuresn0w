/**
 * Fetches SRD spells from Open5e (CC BY 4.0, document slug wotc-srd)
 * and writes src/lib/srd/spells.data.ts for bundling in the app.
 *
 * Run: node scripts/build-srd-spells.mjs
 */

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, "..", "src", "lib", "srd", "spells.data.ts");

function spellId(slug) {
  return String(slug).trim();
}

function normalizeSchool(school) {
  return String(school ?? "Unknown").trim();
}

function normalizeClasses(spell) {
  const lists = Array.isArray(spell.spell_lists) ? spell.spell_lists : [];
  return [...new Set(lists.map((c) => String(c).toLowerCase().trim()).filter(Boolean))].sort();
}

async function fetchAllSpells() {
  const spells = [];
  let url = "https://api.open5e.com/v1/spells/?document__slug=wotc-srd&limit=100";

  while (url) {
    const res = await fetch(url);
    if (!res.ok) {
      throw new Error(`Open5e fetch failed (${res.status}): ${url}`);
    }
    const data = await res.json();
    for (const spell of data.results ?? []) {
      spells.push({
        id: spellId(spell.slug),
        name: String(spell.name).trim(),
        level: Number(spell.spell_level ?? spell.level_int ?? 0),
        school: normalizeSchool(spell.school),
        source: "srd",
        classes: normalizeClasses(spell),
      });
    }
    url = data.next ?? null;
  }

  spells.sort((a, b) => a.level - b.level || a.name.localeCompare(b.name));
  return spells;
}

function emitTs(spells) {
  const body = JSON.stringify(spells, null, 2)
    .replace(/"source": "srd"/g, '"source": "srd" as const')
    .replace(/"classes": \[/g, '"classes": [');

  return `/** Auto-generated by scripts/build-srd-spells.mjs — do not edit by hand. */
import type { SrdSpellEntry } from "./types";

/** ${spells.length} spells from the SRD (Open5e wotc-srd document, CC BY 4.0). */
export const SRD_SPELLS_DATA: readonly SrdSpellEntry[] = ${body.replace(
    /"source": "srd"/g,
    'source: "srd"',
  )} as const;
`;
}

// Fix the JSON output to be valid TypeScript with `as const` on source
function emitTsFixed(spells) {
  const lines = spells.map((s) => {
    const classes = s.classes.map((c) => `"${c}"`).join(", ");
    return `  { id: ${JSON.stringify(s.id)}, name: ${JSON.stringify(s.name)}, level: ${s.level}, school: ${JSON.stringify(s.school)}, source: "srd", classes: [${classes}] },`;
  });

  return `/** Auto-generated by scripts/build-srd-spells.mjs — do not edit by hand. */
import type { SrdSpellEntry } from "./types";

/** ${spells.length} spells from the SRD (Open5e wotc-srd document, CC BY 4.0). */
export const SRD_SPELLS_DATA: readonly SrdSpellEntry[] = [
${lines.join("\n")}
];
`;
}

const spells = await fetchAllSpells();
writeFileSync(OUT, emitTsFixed(spells), "utf8");
console.log(`Wrote ${spells.length} SRD spells to ${OUT}`);
