import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildChapterMarkers, chapterForOffset } from "./srd-chapter-order.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_INDEX = join(__dirname, "..", "src", "lib", "srd", "srdDocumentIndex.data.ts");

const src = readFileSync(join(__dirname, "..", "src", "lib", "srd", "srdDocument.data.ts"), "utf8");
const body = JSON.parse(src.match(/export const SRD_DOCUMENT_BODY: string = ([\s\S]+);\s*$/)[1]);

function normalizeKey(name) {
  return name
    .trim()
    .toLowerCase()
    .replace(/[’']/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

const chapterMarkers = buildChapterMarkers(body);

const headings = [];
const re = /^(#{3,5}) (.+)$/gm;
let match;
while ((match = re.exec(body))) {
  headings.push({
    level: match[1].length,
    title: match[2].trim(),
    start: match.index,
    lineLen: match[0].length,
  });
}

const entries = {};
for (let i = 0; i < headings.length; i++) {
  const h = headings[i];
  let end = body.length;
  for (let j = i + 1; j < headings.length; j++) {
    if (headings[j].level <= h.level) {
      end = headings[j].start;
      break;
    }
  }
  const key = normalizeKey(h.title);
  if (!key) continue;
  const chapter = chapterForOffset(chapterMarkers, h.start);
  const next = { key, title: h.title, start: h.start, end, level: h.level, chapter };
  if (!entries[key]) {
    entries[key] = next;
    continue;
  }
  const prev = entries[key];
  const score = (entry) => {
    let s = 0;
    if (entry.chapter === "spells" && entry.level === 5) s += 10;
    if (entry.chapter === "magic-items" && entry.level === 5) s += 10;
    if (entry.chapter === "monsters-a-z" && entry.level >= 4) s += 8;
    if (entry.chapter === "classes" && entry.level === 3) s += 10;
    if (entry.chapter === "feats" && entry.level === 5) s += 8;
    if (entry.chapter === "character-origins" && entry.level === 3) s += 8;
    if (entry.chapter === "character-origins" && entry.level === 5) s += 6;
    if (entry.chapter === "rules-glossary" && entry.level === 5) s += 6;
    if (entry.chapter === "equipment" && entry.level === 5) s += 5;
    s += Math.max(0, 6 - entry.level);
    return s;
  };
  if (score(next) > score(prev)) entries[key] = next;
}

const list = Object.values(entries).sort((a, b) => a.start - b.start);
writeFileSync(
  OUT_INDEX,
  `/** Auto-generated by scripts/build-srd-document-index.mjs — do not edit by hand. */
import type { SrdDocumentChapterId } from "./srdDocumentLookup";

export type SrdDocumentIndexEntry = {
  key: string;
  title: string;
  start: number;
  end: number;
  level: number;
  chapter: SrdDocumentChapterId;
};

/** Heading index for ${list.length} entries in SRD_CC_v5.2.1. */
export const SRD_DOCUMENT_INDEX: readonly SrdDocumentIndexEntry[] = ${JSON.stringify(list, null, 2)} as const;
`,
  "utf8",
);

const chapterCounts = list.reduce((acc, e) => {
  acc[e.chapter] = (acc[e.chapter] ?? 0) + 1;
  return acc;
}, {});
console.log(`Wrote ${list.length} index entries`, chapterCounts);
