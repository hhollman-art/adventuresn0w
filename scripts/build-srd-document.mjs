import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, "..", "src", "lib", "srd", "srdDocument.data.ts");

const RAW_BASE =
  "https://raw.githubusercontent.com/downfallx/dnd-5e-srd-markdown/master";

/** Chapter order aligned with SRD_CC_v5.2.1 PDF structure. */
const CHAPTERS = [
  { file: "playing-the-game.md", title: "Playing the Game" },
  { file: "character-creation.md", title: "Character Creation" },
  { file: "character-origins.md", title: "Character Origins" },
  { file: "classes.md", title: "Character Classes" },
  { file: "feats.md", title: "Feats" },
  { file: "equipment.md", title: "Equipment" },
  { file: "spells.md", title: "Spells" },
  { file: "rules-glossary.md", title: "Rules Glossary" },
  { file: "gameplay-toolbox.md", title: "Gameplay Toolbox" },
  { file: "magic-items.md", title: "Magic Items" },
  { file: "monsters.md", title: "Monsters" },
  { file: "monsters-A-Z.md", title: "Monsters A–Z" },
  { file: "animals.md", title: "Animals" },
];

function demoteMarkdownHeadings(text, by = 1) {
  return text.replace(/^(#{1,6})\s+/gm, (_, hashes) => {
    const level = Math.min(hashes.length + by, 6);
    return `${"#".repeat(level)} `;
  });
}

function stripLeadingTitle(text, title) {
  const lines = text.replace(/^\uFEFF/, "").trimStart().split("\n");
  if (lines.length === 0) return text;
  const first = lines[0].replace(/^#+\s*/, "").trim();
  if (first.localeCompare(title, undefined, { sensitivity: "accent" }) === 0) {
    return lines.slice(1).join("\n").trimStart();
  }
  return text.trimStart();
}

async function fetchChapter({ file, title }) {
  const url = `${RAW_BASE}/${file}`;
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`Failed to fetch ${url} (${res.status})`);
  }
  const raw = await res.text();
  const body = demoteMarkdownHeadings(stripLeadingTitle(raw, title), 1);
  return {
    id: file.replace(/\.md$/, ""),
    title,
    markdown: `## ${title}\n\n${body}`.trimEnd(),
  };
}

const chapters = [];
for (const chapter of CHAPTERS) {
  chapters.push(await fetchChapter(chapter));
  process.stdout.write(`Fetched ${chapter.file}\n`);
}

const body = chapters.map((c) => c.markdown).join("\n\n");
const chapterMeta = chapters.map(({ id, title }) => ({ id, title }));

const out = `/** Auto-generated by scripts/build-srd-document.mjs — do not edit by hand. */
/** Full English SRD 5.2.1 (SRD_CC_v5.2.1) body — demoted headings for preview carousel (## = page). */

export const SRD_DOCUMENT_PDF_ID = "SRD_CC_v5.2.1" as const;

export const SRD_DOCUMENT_CHAPTERS: readonly { id: string; title: string }[] = ${JSON.stringify(chapterMeta, null, 2)} as const;

/** Combined chapter Markdown (no cover or attribution — added by buildSrdRulesMarkdown). */
export const SRD_DOCUMENT_BODY: string = ${JSON.stringify(body)};
`;

writeFileSync(OUT, out, "utf8");
console.log(
  `Wrote ${chapters.length} chapters (${body.length.toLocaleString()} chars) to ${OUT}`,
);

// Keep the heading index in sync for preview lookups.
await import("./build-srd-document-index.mjs");
await import("./build-srd-entities.mjs");
await import("./consolidate-srd-rules.mjs");
